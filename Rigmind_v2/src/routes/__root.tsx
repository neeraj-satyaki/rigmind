function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

/** Phones (below 768px) get toasts at the top, clear of the safe-area inset;
 *  larger screens keep the usual bottom-right position. */
const TOAST_TOP_OFFSET = "calc(16px + env(safe-area-inset-top))";

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const boot = useBootSequence();
  const isMobile = useIsMobile();
  const toasterProps = isMobile
    ? {
        position: "top-center" as const,
        offset: { top: TOAST_TOP_OFFSET },
        mobileOffset: { top: TOAST_TOP_OFFSET },
      }
    : { position: "bottom-right" as const };

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <AppState>
        <Outlet />
        <Toaster expand visibleToasts={6} gap={10} {...toasterProps} />
        {boot.visible && <BootSplash progress={boot.progress} status={boot.status} done={boot.done} />}
      </AppState>
    </QueryClientProvider>
  );
}
